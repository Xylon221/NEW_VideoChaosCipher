#ifndef ENCRYPTOR_H
#define ENCRYPTOR_H
#include <opencv2/opencv.hpp>
#include <vector>

// ============================================================
// encryptor.h — Logistic 混沌映射加密核心
// ============================================================
// 加密原理:
//   Logistic Map 是最简单的混沌系统:  x_{n+1} = r * x_n * (1 - x_n)
//   当 r 接近 4 (这里用 3.999) 时系统处于完全混沌状态:
//     - 序列对初始值 x_0 极其敏感 (蝴蝶效应)
//     - 序列不可预测 (类随机的确定性序列)
//     - 同一初始值产生完全相同的序列 (可复现 → 可用于解密)
//
// 加密方式:
//   将混沌值映射到 [0,255] 作为密钥字节，与像素的 R/G/B 通道分别 XOR。
//   XOR 是自逆运算: plain ^ key ^ key = plain → 同一函数同时用于加密和解密！
//
// 安全模型:
//   这是一个"流密码" (stream cipher)，种子 (seed) 就是密钥。
//   优点: 速度快，实现简单，原地操作
//   局限: 对已知明文攻击有理论脆弱性 (实际视频帧足够大的情况下难以利用)
// ============================================================

// Logistic Map 迭代函数
// 参数: x ∈ (0,1), r ∈ (0,4]
// 返回: r * x * (1.0 - x)，该值仍在 (0,1) 区间
float logisticMap(float x, float r = 3.999f);

// 加密/解密一帧 (原地操作)
// frame: BGR 彩色图像，调用后内容被加密 (或解密)
// seed:  混沌映射初始种子，范围 (0,1)，默认 0.5
//        同一 seed 加密后再加密 = 恢复原图
void encryptFrame(cv::Mat &frame, float seed = 0.5f);

#endif
